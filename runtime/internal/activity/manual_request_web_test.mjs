import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';

test('manual requests validate drafts, execute once, render persisted failures, and safely reuse history', async () => {
  const require = createRequire(import.meta.url);
  const { JSDOM } = require('jsdom');
  const dom = new JSDOM(await readFile(new URL('./web/index.html', import.meta.url), 'utf8'), { url: 'http://localhost/requests' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, Event: dom.window.Event, Option: dom.window.Option });
  const $ = id => document.getElementById(id);
  dom.window.confirm = () => true;
  const writes = [];
  let release;
  let failure = false;
  let completionCount = 0;
  document.addEventListener('manual-request-completed', () => completionCount++);
  globalThis.fetch = async (path, options = {}) => {
    const input = options.body ? JSON.parse(options.body) : null;
    writes.push({ path, method: options.method, input });
    let body;
    let status = 200;
    if (path === '/api/working-copies/draft-1/discard') return { status: 204, ok: true };
    if (path === '/api/working-copies') body = { ...input, id: 'draft-1', edit_version: 1 };
    else if (path === '/api/working-copies/draft-1') body = { ...input, edit_version: input.edit_version + 1 };
    else if (path === '/api/runs') {
      if (!failure) await new Promise(resolve => { release = resolve; });
      status = failure ? 502 : 201;
      body = { id: 'run-1', trigger_type: 'manual', status: failure ? 'failed' : 'succeeded', request_snapshot: {}, response_status: failure ? undefined : 400, response_body: failure ? null : '{"error":"invalid input"}', response_headers: { 'Content-Type': ['application/json'] }, duration_ms: 12, ...(failure ? { error_message: 'connection refused' } : {}) };
    } else if (path === '/api/runs/history-1') body = { request_snapshot: { method: 'POST', url: 'http://localhost/users', headers: [{ name: 'Authorization', value: '••••••', enabled: true }, { name: 'X-Off', value: 'off', enabled: false }], query_params: [{ name: 'a', value: 'b=c', enabled: true }], body_type: 'json', body: '{}' } };
    else if (path === '/api/runs/auth-history') body = { request_snapshot: { method: 'GET', url: 'http://localhost/users', auth_config: { type: 'bearer', redacted: true } } };
    else throw new Error(`Unexpected API ${path}`);
    return { status, ok: status < 400, json: async () => structuredClone(body) };
  };
  const module = await import('./web/manual-request.js');
  const tick = async () => { for (let i = 0; i < 8; i++) await new Promise(resolve => setImmediate(resolve)); };
  const submit = () => $('manual-form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
  const change = id => $(id).dispatchEvent(new window.Event('change', { bubbles: true }));
  try {
    $('manual-url').value = 'http://localhost/users?existing=1';
    $('manual-method').value = 'POST'; change('manual-method');
    $('manual-body-type').value = 'json'; change('manual-body-type');
    $('manual-body').value = '{invalid';
    submit(); await tick();
    assert.equal(writes.length, 0);
    assert.match($('manual-feedback').textContent, /有效的 JSON/);
    $('manual-body').value = '{"name":"测试"}';
    $('manual-query').value = 'tag=one\ntag=two\nvalue=a=b';
    $('manual-headers').value = 'Authorization: Bearer sample\nX-URL: http://localhost:8080';
    submit(); submit(); await tick();
    assert.equal(writes.filter(item => item.path === '/api/runs').length, 1);
    assert.equal($('manual-fields').disabled, true);
    assert.equal($('manual-reset').disabled, true);
    const request = writes[0].input.request;
    assert.deepEqual(request.query_params.map(row => [row.name, row.value]), [['tag', 'one'], ['tag', 'two'], ['value', 'a=b']]);
    assert.equal(request.headers[1].value, 'http://localhost:8080');
    assert.equal(request.body, '{"name":"测试"}');
    release(); await tick();
    assert.equal(completionCount, 1);
    assert.match($('manual-response').textContent, /HTTP 400/);
    assert.match($('manual-response').textContent, /invalid input/);
    assert.equal($('manual-response').hidden, false);
    assert.equal($('manual-fields').disabled, false);
    assert.equal($('manual-url').value, 'http://localhost/users?existing=1');

    failure = true;
    $('manual-method').value = 'GET'; change('manual-method');
    assert.equal($('manual-body-field').hidden, true);
    submit(); await tick();
    const update = writes.find(item => item.method === 'PUT');
    assert.equal(update.input.edit_version, 1);
    assert.equal(update.input.request.body_type, 'none');
    assert.equal(update.input.request.body, '');
    assert.match($('manual-response').textContent, /connection refused/);
    assert.equal(completionCount, 2);

    await module.loadManualRequest('history-1');
    assert.equal($('manual-body-field').hidden, false);
    assert.equal($('manual-headers').value, 'Authorization: ••••••');
    assert.equal($('manual-query').value, 'a=b=c');
    const before = writes.length;
    submit(); await tick();
    assert.equal(writes.length, before);
    assert.match($('manual-feedback').textContent, /脱敏/);
    $('manual-headers').value = 'Malformed header';
    submit(); await tick();
    assert.equal(writes.length, before);
    assert.match($('manual-feedback').textContent, /Header第 1 行/);
    $('manual-headers').value = '';
    $('manual-url').value = `http://localhost/users?token=${encodeURIComponent('••••••')}`;
    submit(); await tick();
    assert.equal(writes.length, before);
    assert.match($('manual-feedback').textContent, /脱敏/);
    await module.loadManualRequest('auth-history');
    assert.equal($('manual-headers').value, 'Authorization: ••••••');
    const afterLoad = writes.length;
    submit(); await tick();
    assert.equal(writes.length, afterLoad);
    assert.match($('manual-feedback').textContent, /脱敏/);
    $('manual-reset').click(); await tick();
    assert.equal($('manual-url').value, '');
    assert.equal($('manual-response').hidden, true);
  } finally { dom.window.close(); }
});
