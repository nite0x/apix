test('SQL history opens safe details on demand, keeps the inspector open during refresh, filters and recovers from fetch errors', async () => {
  const require = createRequire(import.meta.url);
  const { JSDOM } = require('jsdom');
  const dom = new JSDOM(await readFile(new URL('./web/index.html', import.meta.url), 'utf8'), { url: 'http://localhost/databases' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document });
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  dom.window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new window.Event('close')); };
  let items = [
    { id: 2, connection_id: 'one', connection_name: '测试库', mode: 'query', sql: 'SELECT ? AS value -- <img src=x onerror=alert(1)>', params: ['<script>secret</script>'], status: 'succeeded', started_at: new Date().toISOString(), duration_ms: 2, row_count: 1 },
    { id: 1, connection_id: 'two', connection_name: '另一个库', mode: 'exec', sql: 'UPDATE absent SET name=?', params: ['name'], status: 'failed', error: 'Table absent does not exist <script>', started_at: new Date().toISOString(), duration_ms: 4 },
  ];
  let fail = false;
  globalThis.fetch = async path => ({ ok: !fail, status: fail ? 503 : 200, json: async () => fail ? { error: 'temporarily unavailable' } : path === '/api/database/connections' ? [] : structuredClone(items) });
  const module = await import('./web/databases.js');
  await module.refreshSQLHistory();
  const sqlTab = document.querySelector('#sql-tab');
  const connectionsTab = document.querySelector('#connections-tab');
  assert.equal(document.querySelector('#sql-panel').hidden, false);
  assert.equal(document.querySelector('#connections-panel').hidden, true);
  connectionsTab.click();
  assert.equal(document.querySelector('#sql-panel').hidden, true);
  assert.equal(connectionsTab.getAttribute('aria-selected'), 'true');
  connectionsTab.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }));
  assert.equal(document.activeElement, document.querySelector('#sql-history-tab'));
  assert.equal(document.querySelector('#sql-history-panel').hidden, false);
  document.querySelector('#sql-history-tab').dispatchEvent(new window.KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }));
  assert.equal(document.activeElement, sqlTab);
  assert.equal(document.querySelector('#sql-panel').hidden, false);
  assert.equal(connectionsTab.tabIndex, -1);
  assert.equal(document.querySelectorAll('#sql-executions tr').length, 2);
  assert.match(document.querySelector('#sql-executions').textContent, /返回 1 行/);
  document.querySelectorAll('#sql-executions .sql-statement')[1].click();
  assert.equal(document.querySelector('#sql-result').open, true);
  assert.match(document.querySelector('#sql-result-content').textContent, /Table absent does not exist/);
  assert.equal(document.querySelector('#sql-result-params').textContent, '[\n  "name"\n]');
  assert.equal(document.querySelector('#sql-executions img, #sql-executions script'), null);
  items[0].duration_ms = 3;
  await module.refreshSQLHistory();
  assert.equal(document.querySelector('#sql-result').open, true);
  assert.match(document.querySelector('#sql-result-content').textContent, /Table absent does not exist/);
  document.querySelector('#sql-result-close').click();
  assert.match(document.querySelector('#sql-executions').textContent, /3 ms/);
  const filter = document.querySelector('#sql-connection');
  filter.value = 'two'; filter.dispatchEvent(new window.Event('change'));
  assert.equal(document.querySelectorAll('#sql-executions tr').length, 1);
  assert.match(document.querySelector('#sql-executions').textContent, /另一个库/);
  const search = document.querySelector('#sql-search');
  search.value = 'no match'; search.dispatchEvent(new window.Event('input'));
  assert.match(document.querySelector('#sql-executions').textContent, /没有匹配/);
  search.value = ''; search.dispatchEvent(new window.Event('input'));
  fail = true; await module.refreshSQLHistory();
  assert.equal(document.querySelector('#sql-feedback').hidden, false);
  assert.match(document.querySelector('#sql-executions').textContent, /另一个库/);
  fail = false; await module.refreshSQLHistory();
  assert.equal(document.querySelector('#sql-feedback').hidden, true);
  assert.equal(filter.value, 'two');
  dom.window.close();
});

test('database editor selects PostgreSQL/Hologres defaults and changes an existing driver without replacing its password', async () => {
  const require = createRequire(import.meta.url);
  const { JSDOM } = require('jsdom');
  const dom = new JSDOM(await readFile(new URL('./web/index.html', import.meta.url), 'utf8'), { url: 'http://localhost/databases' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document });
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  dom.window.HTMLDialogElement.prototype.close = function () { this.open = false; };
  const saved = { id: 'holo', name: '分析库', type: 'mysql', host: 'instance.hologres.aliyuncs.com', port: 80, database: 'analytics', username: 'tester' };
  const writes = [];
  globalThis.fetch = async (path, options = {}) => {
    if (options.method === 'PUT') { const input = JSON.parse(options.body); writes.push(input); Object.assign(saved, input); }
    return { ok: true, status: 200, json: async () => options.method === 'PUT' ? structuredClone(saved) : [structuredClone(saved)] };
  };
  const module = await import('./web/databases.js?drivers');
  await module.refreshDatabases();
  const detailToggle = document.querySelector('.database-detail-toggle');
  const detailPanel = document.getElementById(detailToggle.getAttribute('aria-controls'));
  assert.equal(detailPanel.hidden, true);
  detailToggle.click();
  assert.equal(detailPanel.hidden, false);
  assert.equal(detailToggle.getAttribute('aria-expanded'), 'true');
  document.querySelector('[aria-label="编辑 分析库 的连接配置"]').click();
  assert.match(document.querySelector('#database-editor-title').textContent, /编辑/);
  assert.equal(document.querySelector('#database-port').value, '80');
  const type = document.querySelector('#database-type');
  type.value = 'hologres'; type.dispatchEvent(new window.Event('change'));
  assert.equal(document.querySelector('#database-port').value, '80');
  assert.equal(document.querySelector('#database-ssl-field').hidden, false);
  assert.match(document.querySelector('#database-driver-hint').textContent, /\$1/);
  assert.match(document.querySelector('#database-password').placeholder, /保留/);
  document.querySelector('#database-form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true }));
  for (let i = 0; i < 6; i++) await new Promise(resolve => setImmediate(resolve));
  assert.equal(writes[0].type, 'hologres');
  assert.equal(writes[0].ssl_mode, 'prefer');
  assert.equal(Object.hasOwn(writes[0], 'password'), false);
  assert.match(document.querySelector('#databases .badge').textContent, /Hologres/);
  document.querySelector('#database-add').click();
  assert.equal(type.value, 'mysql');
  assert.equal(document.querySelector('#database-port').value, '3306');
  type.value = 'postgresql'; type.dispatchEvent(new window.Event('change'));
  assert.equal(document.querySelector('#database-port').value, '5432');
  type.value = 'hologres'; type.dispatchEvent(new window.Event('change'));
  assert.equal(document.querySelector('#database-port').value, '80');
  document.querySelector('#database-port').value = '6543';
  type.value = 'postgresql'; type.dispatchEvent(new window.Event('change'));
  assert.equal(document.querySelector('#database-port').value, '6543');
  dom.window.close();
});

test('query results load on demand, render values safely, handle empty and legacy results, and retry failures', async () => {
  const require = createRequire(import.meta.url);
  const { JSDOM } = require('jsdom');
  const dom = new JSDOM(await readFile(new URL('./web/index.html', import.meta.url), 'utf8'), { url: 'http://localhost/databases' });
  Object.assign(globalThis, { window: dom.window, document: dom.window.document });
  dom.window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  dom.window.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new window.Event('close')); };
  const item = { id: 42, connection_id: 'one', connection_name: '测试库', mode: 'query', sql: 'SELECT * FROM sample', params: ['<script>secret</script>'], status: 'succeeded', started_at: new Date().toISOString(), duration_ms: 3, row_count: 2 };
  let result = { columns: ['name', 'nullable', 'empty', 'zero', 'flag'], rows: [{ name: '<img src=x onerror=alert(1)>', nullable: null, empty: '', zero: 0, flag: false }], row_count: -1, truncated: true, duration_ms: 3 };
  let fail = false;
  let deferred;
  const paths = [];
  globalThis.fetch = async path => {
    paths.push(path);
    if (path.endsWith('/result')) {
      if (deferred) return deferred;
      return { ok: !fail, status: fail ? 503 : 200, json: async () => fail ? { error: 'temporarily unavailable' } : { result } };
    }
    return { ok: true, json: async () => [item] };
  };
  const module = await import('./web/databases.js?results');
  await module.refreshSQLHistory();
  assert.deepEqual(paths, ['/api/database/executions']);
  const settle = async () => { for (let i = 0; i < 6; i++) await new Promise(resolve => setImmediate(resolve)); };
  const open = async () => { document.querySelector('.sql-result-button').click(); await settle(); };
  const close = () => document.querySelector('#sql-result-close').click();
  await open();
  assert.equal(document.querySelector('#sql-result').open, true);
  assert.equal(paths.at(-1), '/api/database/executions/42/result');
  assert.equal(document.querySelector('#sql-result-statement').textContent, item.sql);
  assert.equal(document.querySelector('#sql-result-params').textContent, JSON.stringify(item.params, null, 2));
  assert.equal(document.querySelector('#sql-result script'), null);
  assert.match(document.querySelector('#sql-result-context').textContent, /测试库/);
  assert.match(document.querySelector('#sql-result-content').textContent, /显示前 1 行.*截断.*总行数未知/);
  assert.deepEqual([...document.querySelectorAll('.sql-result-table th')].map(cell => cell.textContent), result.columns);
  assert.deepEqual([...document.querySelectorAll('.sql-result-table td')].map(cell => cell.textContent), ['<img src=x onerror=alert(1)>', 'NULL', '', '0', 'false']);
  assert.equal(document.querySelector('#sql-result-content img, #sql-result-content script'), null);
  close();
  const longValue = '<script>alert(1)</script>' + '长字段内容'.repeat(100) + '\n第二行完整内容';
  result = { columns: ['evidence', 'lineage'], rows: [{ evidence: longValue, lineage: { source: longValue } }], row_count: 1, duration_ms: 2 };
  await open();
  const preview = document.querySelector('.sql-cell-preview');
  assert.equal(preview.textContent, longValue);
  assert.equal(preview.getAttribute('aria-controls'), 'sql-cell-detail');
  preview.click();
  assert.equal(document.querySelector('#sql-cell-detail').open, true);
  assert.equal(document.querySelector('#sql-cell-context').textContent, '第 1 行 · evidence');
  assert.equal(document.querySelector('#sql-cell-value').textContent, longValue);
  assert.equal(document.querySelector('#sql-cell-detail script'), null);
  document.querySelector('#sql-cell-close').click();
  assert.equal(document.querySelector('#sql-cell-detail').open, false);
  assert.equal(document.querySelector('#sql-cell-value').textContent, '');
  assert.equal(document.querySelector('#sql-result').open, true);
  document.querySelectorAll('.sql-cell-preview')[1].click();
  assert.equal(document.querySelector('#sql-cell-value').textContent, JSON.stringify({ source: longValue }));
  close();
  assert.equal(document.querySelector('#sql-cell-detail').open, false);
  result = { columns: ['name'], rows: [], row_count: 0, truncated: false, duration_ms: 1 };
  await open();
  assert.match(document.querySelector('#sql-result-content').textContent, /返回 0 行.*没有返回数据/);
  assert.equal(document.querySelector('.sql-result-table th').textContent, 'name');
  close(); result = null; await open();
  assert.match(document.querySelector('#sql-result-content').textContent, /未保存查询结果.*重新执行/);
  close(); fail = true; await open();
  assert.match(document.querySelector('#sql-result-content [role="alert"]').textContent, /temporarily unavailable/);
  fail = false; result = { columns: ['value'], rows: [{ value: 'recovered' }], row_count: 1, duration_ms: 2 };
  document.querySelector('#sql-result-content button').click(); await settle();
  assert.match(document.querySelector('#sql-result-content').textContent, /recovered/);
  close();
  let resolve;
  deferred = new Promise(done => { resolve = done; });
  await open(); close();
  resolve({ ok: true, json: async () => ({ result }) }); await settle();
  assert.equal(document.querySelector('#sql-result-content').textContent, '');
  dom.window.close();
});
